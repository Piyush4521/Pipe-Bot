"""Pydantic Schemas for AI Inference Results and Defect Events.

Defines schemas for bounding boxes, inference results, model metadata,
and defect detection events generated by the vision processing pipeline.
"""

from typing import List, Optional
from pydantic import BaseModel, ConfigDict, Field
from pydantic.alias_generators import to_camel

from app.models.defect import DefectClass


class BoundingBoxSchema(BaseModel):
    """Normalized bounding box coordinates (0.0 to 1.0) matching frontend contract."""

    x: float = Field(..., ge=0.0, le=1.0, description="Normalized top-left X coordinate")
    y: float = Field(..., ge=0.0, le=1.0, description="Normalized top-left Y coordinate")
    width: float = Field(..., ge=0.0, le=1.0, description="Normalized box width")
    height: float = Field(..., ge=0.0, le=1.0, description="Normalized box height")

    model_config = ConfigDict(
        alias_generator=to_camel,
        populate_by_name=True,
    )


class InferenceResult(BaseModel):
    """Structured detection output generated by the YOLO inference interface."""

    detection_id: str = Field(..., description="Unique detection identifier")
    frame_id: str = Field(..., description="Identifier of the optical frame containing anomaly")
    inspection_id: Optional[str] = Field(None, description="Active inspection identifier")
    defect_class: DefectClass = Field(..., description="Target anomaly classification")
    confidence: float = Field(..., ge=0.0, le=1.0, description="Model confidence score (0.0 to 1.0)")
    bounding_box: BoundingBoxSchema = Field(..., description="Normalized bounding box coordinates")
    inference_timestamp: str = Field(..., description="UTC ISO 8601 timestamp when inference completed")
    capture_timestamp: Optional[str] = Field(None, description="Optical capture timestamp from camera")
    image_reference: Optional[str] = Field(None, description="Relative path to cropped evidence image")
    estimated_distance_meters: Optional[float] = Field(
        None, ge=0.0, description="Estimated linear distance in conduit from encoder association"
    )
    localization_status: str = Field(
        "unlocalized",
        description="Localization state: localized | unavailable | unlocalized",
    )
    localization_reason: Optional[str] = Field(
        None, description="Detailed explanation if localization is unavailable"
    )

    model_config = ConfigDict(
        alias_generator=to_camel,
        populate_by_name=True,
    )


class InferenceStatusResponse(BaseModel):
    """Operational status report for the computer vision inference engine."""

    provider: str = Field(..., description="Active inference provider name: unavailable | ultralytics")
    is_available: bool = Field(..., description="Whether inference engine is operational")
    model_path: Optional[str] = Field(None, description="Configured path to custom model weights")
    device: str = Field("cpu", description="Execution device: cpu | cuda")
    confidence_threshold: float = Field(..., ge=0.0, le=1.0, description="Minimum detection confidence")
    expected_classes: List[str] = Field(..., description="Authorized target defect classes")
    status: str = Field(..., description="Operational summary message")
    timestamp: str = Field(..., description="Evaluation timestamp in ISO 8601 UTC")

    model_config = ConfigDict(
        alias_generator=to_camel,
        populate_by_name=True,
    )

